test('copy works and clipboard denial offers selectable usage', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/showcase')
  await category(page, 'Icons').click()
  await page.getByRole('button', { name: 'Copy folder identity icon usage', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain('<Icon name="folder" tone="color" />')
  await category(page, 'Artwork').click()
  await page.getByRole('button', { name: 'View monochrome' }).click()
  await page.getByRole('button', { name: 'Copy primary-poster background usage', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain('tone="mono"')
  await page.evaluate(() => {
    Object.defineProperty(navigator.clipboard, 'writeText', { value: () => Promise.reject(new Error('denied')) })
  })
  await page.getByRole('button', { name: 'Copy primary-poster background usage', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Copy usage manually' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Usage example' })).toHaveValue(/<Background name="primary-poster" tone="mono"/)
})

