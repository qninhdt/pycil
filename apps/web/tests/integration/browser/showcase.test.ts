test('authored icons show distinct color and mono drawings and copy usage', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/showcase')
  await category(page, 'Icons').click()
  await expect(page.getByRole('heading', { name: 'One icon language.' })).toBeVisible()
  await expect(page.locator('#identity-icons .icon-tile')).toHaveCount(54)
  await expect(page.locator('#control-icons .icon-tile')).toHaveCount(54)
  await expect(page.locator('#learning-icons .icon-tile')).toHaveCount(11)
  const invalid = await page.locator('.icon-tile').evaluateAll(tiles => tiles.flatMap((tile, index) => {
    const [color, mono] = tile.querySelectorAll('svg.catalog-icon')
    return color && mono && color.getAttribute('viewBox') === mono.getAttribute('viewBox')
      && color.childElementCount > 0 && mono.childElementCount > 0 ? [] : [index]
  }))
  expect(invalid).toEqual([])
  const firstPair = page.locator('.icon-tile').first().locator('svg.catalog-icon')
  await expect(firstPair.nth(0)).toHaveAttribute('data-tone', 'color')
  await expect(firstPair.nth(1)).toHaveAttribute('data-tone', 'mono')
  expect(await firstPair.nth(0).innerHTML()).not.toBe(await firstPair.nth(1).innerHTML())
  await page.getByRole('textbox', { name: 'Filter catalog' }).fill('folder')
  await expect(page.getByRole('button', { name: 'Copy folder control icon usage', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Copy folder control icon usage', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain("<Icon name=\"folder\" variant=\"control\" tone=\"mono\" />")
  await page.getByRole('textbox', { name: 'Filter catalog' }).fill('not-a-real-icon')
  await expect(page.getByRole('heading', { name: 'No matching icons' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Filter catalog' }).fill('')
  await expect(page.locator('.catalog-icon')).toHaveCount(await page.locator('.icon-tile').count() * 2)
  await page.setViewportSize({ width: 320, height: 900 })
  await overflowCheck(page)
  expect(errors).toEqual([])
})
