import { test, expect } from '../../fixtures/index.ts'

test('publication needs consent and unpublishing revokes guest and saved-reference access', async ({ user, secondary, data, vocabulary, guest }) => {
  const deck = await data.create({ name: `Public travel ${user.subject.slice(-8)}`, type: 'deck', sense_ids: [vocabulary.bankRiver.sense_id] })
  let referenceId: string | undefined
  const errors: unknown[] = []
  try {
    await user.page.goto(`/app/personal/${deck.id}`)
    const actions = user.page.getByRole('button', { name: `Actions for ${deck.name}` })
    await actions.click()
    await user.page.getByRole('menuitem', { name: 'Publish', exact: true }).click()
    await user.page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
    await guest.goto(`/u/${user.account.id}/${deck.id}`)
    await expect(guest.getByRole('heading', { level: 1 })).not.toContainText(deck.name)
    await actions.click()
    await user.page.getByRole('menuitem', { name: 'Publish', exact: true }).click()
    await user.page.getByRole('alertdialog').getByRole('button', { name: 'Publish', exact: true }).click()
    await expect(user.page).toHaveURL(new RegExp(`/app/published/${deck.id}$`))
    await guest.reload()
    await expect(guest.getByRole('heading', { level: 1 })).toContainText(deck.name)
    const reference = await secondary.api.call<{ id: string }>('nodes', 'POST', { type: 'reference', reference_id: deck.id, parent_id: secondary.account.personal_node_id, name: 'Saved river words' }, 201)
    referenceId = reference.id
    await secondary.page.goto(`/app/personal/${reference.id}`)
    await expect(secondary.page.getByRole('heading', { level: 1 })).toContainText('Saved river words')
    await user.page.getByRole('button', { name: `Settings for ${deck.name}` }).click()
    await user.page.getByRole('menuitem', { name: 'Move to Personal', exact: true }).click()
    await user.page.getByRole('alertdialog').getByRole('button', { name: 'Move to Personal', exact: true }).click()
    await expect(user.page).toHaveURL(new RegExp(`/app/personal/${deck.id}$`))
    await guest.reload()
    await expect(guest.getByRole('heading', { level: 1 })).not.toContainText(deck.name)
    await secondary.page.reload()
    await expect(secondary.page.getByText('Reference unavailable.', { exact: true })).toBeVisible()
    expect(await secondary.api.call<{ reference_available: boolean }>(`nodes/${reference.id}`)).toMatchObject({ reference_available: false })
  } catch (error) { errors.push(error) }
  const results = await Promise.allSettled([referenceId ? secondary.api.call(`nodes/${referenceId}`, 'DELETE', undefined, [204, 404]) : undefined])
  errors.push(...results.filter(result => result.status === 'rejected').map(result => result.reason))
  if (errors.length) throw new AggregateError(errors, 'Publication journey failed')
})

test('publishing a subtree retains its Personal reference and deleting it revokes descendant guest access', async ({ user, data, vocabulary, guest }) => {
  const folder = await data.create({ name: 'Shared finance folder', type: 'folder' })
  const deck = await data.create({ name: 'Shared finance descendant', type: 'deck', parent_id: folder.id, sense_ids: [vocabulary.bankFinancial.sense_id] })
  await user.page.goto(`/app/personal/${folder.id}`)
  let settings = user.page.getByRole('button', { name: `Actions for ${folder.name}`, exact: true })
  await settings.click()
  await user.page.getByRole('menuitem', { name: 'Publish', exact: true }).click()
  await user.page.getByRole('checkbox', { name: 'Keep a reference in Personal', exact: true }).check()
  await user.page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await guest.goto(`/u/${user.account.id}/${deck.id}`)
  await expect(guest.getByRole('heading', { level: 1 })).not.toContainText(deck.name)
  await settings.click()
  await user.page.getByRole('menuitem', { name: 'Publish', exact: true }).click()
  await user.page.getByRole('checkbox', { name: 'Keep a reference in Personal', exact: true }).check()
  await user.page.getByRole('alertdialog').getByRole('button', { name: 'Publish', exact: true }).click()
  await expect(user.page).toHaveURL(new RegExp(`/app/published/${folder.id}$`))
  settings = user.page.getByRole('button', { name: `Settings for ${folder.name}`, exact: true })
  const personal = await user.api.call<{ nodes: { id: string; reference_id?: string }[] }>(`nodes?parent_id=${user.account.personal_node_id}`)
  const retained = personal.nodes.filter(node => node.reference_id === folder.id)
  expect(retained).toHaveLength(1)
  data.track(retained[0].id)
  await guest.goto(`/u/${user.account.id}/${folder.id}`)
  await guest.getByRole('link', { name: deck.name, exact: true }).click()
  await expect(guest.getByRole('heading', { level: 1 })).toContainText(deck.name)
  await settings.click()
  await user.page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await user.page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await guest.reload()
  await expect(guest.getByRole('heading', { level: 1 })).toContainText(deck.name)
  await settings.click()
  await user.page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await user.page.getByRole('alertdialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(async () => {
    await guest.reload()
    await expect(guest.getByRole('heading', { level: 1 })).not.toContainText(deck.name)
  }).toPass()
  expect(await user.api.call(`nodes/${retained[0].id}`)).toMatchObject({ reference_available: false })
})
