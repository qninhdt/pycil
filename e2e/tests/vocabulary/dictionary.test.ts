test('the word picker retains selections across searches and preserves a concurrent addition', async ({ actor, data, vocabulary }) => {
  const deck = await data.create({ name: 'Selected meanings', type: 'deck' })
  await actor.page.goto(`/app/personal/${deck.id}/words`)
  await actor.page.getByRole('button', { name: 'Add words', exact: true }).click()
  const picker = actor.page.getByRole('dialog', { name: 'Add words to deck', exact: true })
  const search = picker.getByRole('searchbox', { name: 'Search words', exact: true })
  await search.fill('bank')
  await picker.getByRole('checkbox', { name: /an institution where people keep and borrow money/ }).check()
  await search.fill('archive')
  await picker.getByRole('checkbox', { name: /a collection of historical records/ }).check()
  await expect(picker.getByText('2 meanings selected', { exact: true })).toBeVisible()
  await actor.api.call(`nodes/${deck.id}:modifySenses`, 'POST', { add: [vocabulary.bankRiver.sense_id], remove: [] })
  await picker.getByRole('button', { name: 'Add to deck', exact: true }).click()
  await expect(picker).not.toBeVisible()
  const senses = await actor.api.call<{ senses: { sense_id: number }[] }>(`nodes/${deck.id}/senses`)
  expect(senses.senses.map(sense => sense.sense_id).sort((a, b) => a - b)).toEqual([vocabulary.bankFinancial.sense_id, vocabulary.bankRiver.sense_id, vocabulary.archiveCollection.sense_id].sort((a, b) => a - b))
})

test('adding a Dictionary meaning can create a deck in a nested folder', async ({ actor, data, vocabulary }) => {
  const folder = await data.create({ name: 'Dictionary destination', type: 'folder' })
  await actor.page.goto(`/app/dictionary?q=bank&word=${vocabulary.bankFinancial.word_id}`)
  await actor.page.locator('article section').filter({ hasText: 'an institution where people keep and borrow money' }).getByRole('button', { name: 'Add to deck', exact: true }).click()
  const destination = actor.page.getByRole('dialog', { name: 'Choose a destination', exact: true })
  await destination.getByRole('button', { name: 'Personal', exact: true }).click()
  await destination.getByRole('button', { name: folder.name, exact: true }).click()
  await destination.getByRole('button', { name: `Create a deck in ${folder.name}`, exact: true }).click()
  await destination.getByRole('textbox', { name: 'New deck name', exact: true }).fill('Created from Dictionary')
  const created = actor.page.waitForResponse(response => response.url().endsWith('/v1/nodes') && response.request().method() === 'POST')
  await destination.getByRole('button', { name: 'Create and add', exact: true }).click()
  const response = await created
  expect(response.status()).toBe(201)
  const deck = await response.json()
  data.track(deck.id)
  expect(deck).toMatchObject({ name: 'Created from Dictionary', parent_id: folder.id, sense_ids: [vocabulary.bankFinancial.sense_id] })
  await actor.page.goto(`/app/personal/${deck.id}/words`)
  await expect(actor.page.getByRole('button', { name: /View bank: an institution/ })).toBeVisible()
})

test('native aliases and inflections find ready words and reveal the matching lexical detail', async ({ actor }) => {
  await actor.page.goto('/app/dictionary?q=colour')
  await actor.page.getByRole('button', { name: /color.*Ready/ }).click()
  await expect(actor.page.locator('article')).toContainText('colour')
  await actor.page.getByRole('searchbox', { name: 'Search word or expression', exact: true }).fill('banking')
  await actor.page.getByRole('button', { name: /bank.*Matched.*banking/ }).click()
  await actor.page.getByRole('tab', { name: /^verb/ }).click()
  await expect(actor.page.locator('article')).toContainText('to put money into a bank account')
  await expect(actor.page.locator('article')).toContainText('banking')
  await expect(actor.page.locator('article')).toContainText('banked')
})
