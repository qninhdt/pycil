import { test, expect } from '../../fixtures/index.ts'

test('a ready word exposes distinct meanings and adds the selected meaning to an existing deck', async ({ actor, data, vocabulary }) => {
  const deck = await data.create({ name: 'Dictionary additions', type: 'deck' })
  await actor.page.goto(`/app/dictionary?q=bank&word=${vocabulary.bankFinancial.word_id}`)
  await expect(actor.page.getByRole('heading', { name: 'bank', exact: true })).toBeVisible()
  await expect(actor.page.locator('article')).toContainText('an institution where people keep and borrow money')
  await expect(actor.page.locator('article')).toContainText('the ground along the side of a river')
  const sense = actor.page.locator('article section').filter({ hasText: 'an institution where people keep and borrow money' })
  await sense.getByRole('button', { name: 'Add to deck', exact: true }).click()
  const dialog = actor.page.getByRole('dialog', { name: 'Choose a destination', exact: true })
  await dialog.getByRole('button', { name: 'Personal', exact: true }).click()
  await dialog.getByRole('button', { name: `${deck.name} Deck`, exact: true }).click()
  await dialog.getByRole('button', { name: 'Add to deck', exact: true }).click()
  await expect(actor.page.getByText('Meaning added to deck', { exact: true })).toBeVisible()
  const contents = await actor.api.call<{ senses: { sense_id: number }[] }>(`nodes/${deck.id}/senses`)
  expect(contents.senses.map(item => item.sense_id)).toEqual([vocabulary.bankFinancial.sense_id])
})

