import { test, expect } from '../../fixtures/index.ts'
import { answerChoice, finishStudy, selectQuestions } from '../../support/study.ts'

test('a new account shows empty state and study updates deduplicated counts and activity', async ({ actor, data, vocabulary }) => {
  await expect(actor.page.getByRole('heading', { name: 'Your Library starts here.', exact: true })).toBeVisible()
  await expect(actor.page.getByRole('link', { name: 'Create a deck', exact: true })).toHaveAttribute('href', '/app/personal?create=deck')
  await selectQuestions(actor)
  await actor.api.call('me/settings', 'PATCH', { timezone: 'Pacific/Honolulu' })
  await data.create({ name: 'Home finances', type: 'deck', sense_ids: [vocabulary.bankFinancial.sense_id] })
  await data.create({ name: 'Home duplicate membership', type: 'deck', sense_ids: [vocabulary.bankFinancial.sense_id] })
  await actor.page.reload()
  const today = actor.page.getByRole('region', { name: 'Today', exact: true })
  await expect(today.locator('dl')).toContainText('1')
  const learn = today.getByRole('link', { name: 'Learn new', exact: true })
  await expect(learn).toHaveAttribute('href', /selection=new$/)
  await learn.click()
  await answerChoice(actor.page, 'bank')
  await finishStudy(actor.page)
  await actor.page.goto('/app')
  expect(await actor.api.call('study/progress')).toMatchObject({ total: 1, studied: 1, new: 0 })
  const activity = await actor.api.call<{ timezone: string; applied_events: number; days: { day: string }[] }>('study/activity')
  expect(activity).toMatchObject({ timezone: 'Pacific/Honolulu', applied_events: 1 })
  await expect(actor.page.getByRole('region', { name: 'Study activity', exact: true })).toContainText('1')
  await expect(today.getByRole('link', { name: 'Practice', exact: true })).toBeVisible()
})
