import { test, expect } from '../../fixtures/index.ts'
import { openAssistant, sendMessage } from '../../support/assistant.ts'

test('a real assistant reads via tools, reopens its checkpoint and writes only after approval', async ({ user, data, vocabulary }) => {
  test.setTimeout(300_000)
  const source = await data.create({ name: 'Live financial vocabulary', type: 'deck', sense_ids: [vocabulary.bankFinancial.sense_id] })
  await user.page.goto(`/app/personal/${source.id}`)
  await openAssistant(user.page)
  const readRun = user.page.waitForResponse(response => response.url().endsWith('/assistant:run') && response.request().method() === 'POST', { timeout: 150_000 })
  await sendMessage(user.page, `Use read_library to read deck ${source.id}, then briefly explain the meaning in it. Do not modify anything.`)
  expect((await readRun).status()).toBe(200)
  await expect(user.page.getByRole('button', { name: 'Send message', exact: true })).toBeVisible({ timeout: 150_000 })
  const history = await user.api.call<{ conversations: { id: string }[] }>('assistant/conversations')
  expect(history.conversations).toHaveLength(1)
  const conversationId = history.conversations[0].id
  const details = await user.api.call<{ state: { messages: { role: string; content: unknown }[] } }>(`assistant/conversations/${conversationId}`)
  const tools = details.state.messages.filter(message => message.role === 'tool')
  expect(tools.length).toBeGreaterThan(0)
  expect(JSON.stringify(tools)).toContain('an institution where people keep and borrow money')
  await sendMessage(user.page, 'Give one short example using that financial meaning. Do not modify the Library.')
  await expect(user.page.getByRole('button', { name: 'Send message', exact: true })).toBeVisible({ timeout: 150_000 })
  await user.page.reload()
  await openAssistant(user.page)
  await expect(user.page.getByRole('complementary', { name: 'PycilAI', exact: true })).toContainText('bank')
  const name = `Approved finance ${user.subject.slice(-8)}`
  await sendMessage(user.page, `Use create_node to create a deck named "${name}" in Personal (${user.account.personal_node_id}) with sense_ids [${vocabulary.bankFinancial.sense_id}]. Do not call any other mutation tool.`)
  await expect(user.page.getByRole('button', { name: 'Approve changes', exact: true })).toBeVisible({ timeout: 150_000 })
  expect(await user.api.call(`nodes/${user.account.personal_node_id}:search?q=${encodeURIComponent(name)}`)).toMatchObject({ nodes: [] })
  await user.page.getByRole('button', { name: 'Approve changes', exact: true }).click()
  await expect(user.page.getByRole('button', { name: 'Send message', exact: true })).toBeVisible({ timeout: 150_000 })
  const found = await user.api.call<{ nodes: { id: string }[] }>(`nodes/${user.account.personal_node_id}:search?q=${encodeURIComponent(name)}`)
  expect(found.nodes).toHaveLength(1)
  data.track(found.nodes[0].id)
  expect(await user.api.call(`study/progress?node_id=${found.nodes[0].id}`)).toMatchObject({ total: 1 })
})
