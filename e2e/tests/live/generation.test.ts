import { test, expect } from '../../fixtures/index.ts'
import { selectQuestions, startStudy, answerChoice, finishStudy } from '../../support/study.ts'

test('real generation normalizes an inflected reference, updates search and supports adding a readable meaning', async ({ user, data }) => {
  test.setTimeout(300_000)
  const deck = await data.create({ name: 'Live harbor vocabulary', type: 'deck' })
  await user.page.goto('/app/dictionary?q=harbours')
  await user.page.getByRole('button').filter({ hasText: /harbou?r.*Generate/ }).click()
  await user.page.getByRole('button', { name: 'Prepare entry', exact: true }).click()
  await expect(user.page.locator('article').getByRole('heading', { level: 2 })).toHaveText('harbor', { timeout: 240_000 })
  const search = await user.api.call<{ items: { kind: string; word_id: number; lemma: string }[] }>('words:search?query=harbour&include_reference=true')
  expect(search.items[0]).toMatchObject({ kind: 'word', lemma: 'harbor' })
  const word = await user.api.call<{ lemma: string; senses: { id: number; definition: { content: string }; examples: { content: string }[] }[] }>(`words/${search.items[0].word_id}`)
  expect(word.senses.length).toBeGreaterThan(0)
  for (const sense of word.senses) {
    expect(sense.definition.content.trim().length).toBeGreaterThan(15)
    expect(sense.examples.length).toBeGreaterThan(0)
  }
  const firstSense = user.page.locator('article section').filter({ hasText: word.senses[0].definition.content })
  await firstSense.getByRole('button', { name: 'Add to deck', exact: true }).click()
  const destination = user.page.getByRole('dialog', { name: 'Choose a destination', exact: true })
  await destination.getByRole('button', { name: 'Personal', exact: true }).click()
  await destination.getByRole('button', { name: `${deck.name} Deck`, exact: true }).click()
  await destination.getByRole('button', { name: 'Add to deck', exact: true }).click()
  await expect(user.page.getByText('Meaning added to deck', { exact: true })).toBeVisible()
  expect(await user.api.call(`study/progress?node_id=${deck.id}`)).toMatchObject({ total: 1, studied: 0 })
  await user.page.goto(`/app/flashcards?node=${deck.id}`)
  await user.page.getByRole('button', { name: 'Reveal meaning of harbor', exact: true }).click()
  await expect(user.page.locator('article[data-face="back"]')).toContainText(word.senses[0].definition.content)
  await selectQuestions(user)
  await startStudy(user.page, deck.id)
  await answerChoice(user.page, 'harbor')
  await finishStudy(user.page)
  expect(await user.api.call(`study/progress?node_id=${deck.id}`)).toMatchObject({ studied: 1 })
})
