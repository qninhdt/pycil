import assert from 'node:assert/strict'
import { mkdir, mkdtemp, writeFile, readFile, access, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import { cleanBuild } from './clean.ts'
import { prepareBuild } from './prepare-web.ts'

const id = 'cleanupfixture1234'

for (const original of ['development declarations\n', null]) {
  test(`cleanup restores ${original === null ? 'absent' : 'existing'} Next declarations after a failed build`, async () => {
    const web = await mkdtemp(join(tmpdir(), 'pycil-e2e-clean-'))
    try {
      await mkdir(`${web}/.e2e`)
      if (original !== null) await writeFile(`${web}/next-env.d.ts`, original)
      await prepareBuild(web, id)
      await assert.rejects(prepareBuild(web, id), { code: 'EEXIST' })
      await writeFile(`${web}/next-env.d.ts`, `import './.e2e/${id}/next/types/routes.d.ts';\n`)
      await assert.rejects(cleanBuild('../outside', web), /recorded E2E run ID/)
      await access(`${web}/.e2e/${id}/tsconfig.json`)
      await cleanBuild(id, web)
      if (original === null) await assert.rejects(access(`${web}/next-env.d.ts`), { code: 'ENOENT' })
      else assert.equal(await readFile(`${web}/next-env.d.ts`, 'utf8'), original)
      await assert.rejects(access(`${web}/.e2e/${id}`), { code: 'ENOENT' })
      await cleanBuild(id, web)
    } finally { await rm(web, { recursive: true, force: true }) }
  })
}

test('cleanup preserves another run and declarations regenerated by development', async () => {
  const web = await mkdtemp(join(tmpdir(), 'pycil-e2e-clean-'))
  try {
    await mkdir(`${web}/.e2e`)
    await prepareBuild(web, id)
    await mkdir(`${web}/.e2e/anotherfixture1234`)
    await writeFile(`${web}/next-env.d.ts`, 'new development declarations\n')
    await cleanBuild(id, web)
    assert.equal(await readFile(`${web}/next-env.d.ts`, 'utf8'), 'new development declarations\n')
    await access(`${web}/.e2e/anotherfixture1234`)
  } finally { await rm(web, { recursive: true, force: true }) }
})

test('cleanup with E2E_CACHE_BUILD=1 preserves build-cache directory and restores declarations', async () => {
  const previousEnv = process.env.E2E_CACHE_BUILD
  process.env.E2E_CACHE_BUILD = '1'
  const web = await mkdtemp(join(tmpdir(), 'pycil-e2e-clean-cache-'))
  try {
    await mkdir(`${web}/.e2e`)
    await writeFile(`${web}/next-env.d.ts`, 'initial declarations\n')
    await prepareBuild(web, id)
    // prepareBuild is idempotent when caching is enabled
    await prepareBuild(web, id)
    await writeFile(`${web}/next-env.d.ts`, `import './.e2e/build-cache/next/types/routes.d.ts';\n`)
    await access(`${web}/.e2e/build-cache/tsconfig.json`)
    await cleanBuild(id, web)
    assert.equal(await readFile(`${web}/next-env.d.ts`, 'utf8'), 'initial declarations\n')
    // cleanBuild is idempotent
    await cleanBuild(id, web)
    assert.equal(await readFile(`${web}/next-env.d.ts`, 'utf8'), 'initial declarations\n')
    // build-cache must still exist
    await access(`${web}/.e2e/build-cache/tsconfig.json`)

    // updating clean declarations updates the backup
    await writeFile(`${web}/next-env.d.ts`, 'updated clean declarations\n')
    await prepareBuild(web, id)
    await writeFile(`${web}/next-env.d.ts`, `import './.e2e/build-cache/next/types/routes.d.ts';\n`)
    // repeat prepareBuild while dirty does not overwrite the clean backup
    await prepareBuild(web, id)
    await cleanBuild(id, web)
    assert.equal(await readFile(`${web}/next-env.d.ts`, 'utf8'), 'updated clean declarations\n')
    await access(`${web}/.e2e/build-cache/tsconfig.json`)
  } finally {
    if (previousEnv === undefined) delete process.env.E2E_CACHE_BUILD
    else process.env.E2E_CACHE_BUILD = previousEnv
    await rm(web, { recursive: true, force: true })
  }
})
