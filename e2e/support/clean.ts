import type { Reporter } from '@playwright/test/reporter'
import { readFile, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { root, directory, runId } from './environment.ts'
import { requireFreePort } from './stack.ts'
import { buildDirectory } from './prepare-web.ts'

export async function cleanBuild(id: string, web = `${root}/apps/web`) {
  const directory = buildDirectory(web, id)
  const nextEnvPath = `${web}/next-env.d.ts`
  const current = await readFile(nextEnvPath, 'utf8').catch((error: NodeJS.ErrnoException) => {
    if (error.code !== 'ENOENT') throw error
    return null
  })
  // Never overwrite declarations regenerated by a different Next process.
  if (current?.includes(`./.e2e/${id}/next/`)) {
    const original: unknown = JSON.parse(await readFile(`${directory}/next-env.json`, 'utf8'))
    if (original !== null && typeof original !== 'string') throw new Error('Invalid Next declarations backup')
    if (original === null) await rm(nextEnvPath, { force: true })
    else await writeFile(nextEnvPath, original)
  }
  await rm(directory, { recursive: true, force: true })
}

async function cleanStoppedBuild(id: string) {
  buildDirectory(`${root}/apps/web`, id)
  await requireFreePort(3200)
  await cleanBuild(id)
}

// Reporters finish after Playwright stops its webServer; global teardown runs before it.
export default class BuildCleanup implements Reporter {
  printsToStdio() { return false }
  async onEnd() { await cleanStoppedBuild(runId) }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const id = process.argv[2]
  if (!id || !/^[a-z0-9]{12,40}$/.test(id)) throw new Error('Pass one recorded E2E run ID')
  const status = JSON.parse(await readFile(`${directory}/.artifacts/${id}/cleanup.json`, 'utf8')) as { completed?: boolean }
  if (status.completed !== true) throw new Error('The run does not have a successful cleanup record')
  await cleanStoppedBuild(id)
  console.log(`Removed completed run ${id} build output; private diagnostics retained.`)
}
