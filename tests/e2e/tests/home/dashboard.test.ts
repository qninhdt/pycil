import { test, expect } from '../../fixtures/index.ts'
import { answerChoice, finishStudy, selectQuestions } from '../../support/study.ts'

test('a new account shows empty state and study updates deduplicated counts and activity', async ({ user, data, vocabulary }) => {
  await expect(user.page.getByRole('heading', { name: 'Your Library starts here.', exact: true })).toBeVisible()
  await expect(user.page.getByRole('link', { name: 'Create a deck', exact: true })).toHaveAttribute('href', '/app/personal?create=deck')
  await selectQuestions(user)
  await user.api.call('me/settings', 'PATCH', { timezone: 'Pacific/Honolulu' })
  await data.create({ name: 'Home finances', type: 'deck', sense_ids: [vocabulary.bankFinancial.sense_id] })
  await data.create({ name: 'Home duplicate membership', type: 'deck', sense_ids: [vocabulary.bankFinancial.sense_id] })
  await user.page.reload()
  const today = user.page.getByRole('region', { name: 'Today', exact: true })
  await expect(today.locator('dl')).toContainText('1')
  const learn = today.getByRole('link', { name: 'Learn new', exact: true })
  await expect(learn).toHaveAttribute('href', /selection=new$/)
  await learn.click()
  await answerChoice(user.page, 'bank')
  await finishStudy(user.page)
  await user.page.goto('/app')
  expect(await user.api.call('study/progress')).toMatchObject({ total: 1, studied: 1, new: 0, not_due: 1, due: 0 })
  const activity = await user.api.call<{ timezone: string; applied_events: number; current_streak: number; longest_streak: number; days: { day: string }[] }>('study/activity')
  expect(activity).toMatchObject({ timezone: 'Pacific/Honolulu', applied_events: 1, current_streak: 1, longest_streak: 1 })
  const streak = user.page.locator('section[aria-labelledby="home-streak-title"]')
  await expect(streak.locator('#home-streak-title')).toBeVisible()
  await expect(streak.locator('.home-streak-number strong')).toHaveText('1')
  await expect(streak.locator('.home-streak-number')).toContainText('day')
  const sevenDays = streak.locator('div[aria-label="Activity over the last seven days"]')
  await expect(sevenDays.locator('> div')).toHaveCount(7)
  await expect(sevenDays.locator('[data-active="true"]')).toHaveCount(1)
  await expect(sevenDays.locator('[data-active="false"]')).toHaveCount(6)
  await expect(sevenDays.locator('[data-active="true"][data-today="true"]')).toBeVisible()
  await expect(streak).toContainText('Longest streak')
  await expect(streak).toContainText('1 day')
  await expect(user.page.getByRole('region', { name: 'Study activity', exact: true })).toContainText('1')
  await expect(today.getByRole('link', { name: 'Practice', exact: true })).toBeVisible()
})
